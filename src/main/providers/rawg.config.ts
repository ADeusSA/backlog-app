/**
 * Ключ RAWG, вшитый в сборку (08 §4).
 *
 * Владелец сборки один раз кладёт свой ключ в файл `.env` рядом с package.json:
 *
 *     MAIN_VITE_RAWG_KEY=ваш_ключ_с_rawg.io/apidocs
 *
 * Vite подставляет значение при сборке, поэтому у тех, кому вы отдадите готовый архив,
 * заполнение из RAWG работает сразу — свой ключ заводить не нужно.
 *
 * ВАЖНО, что нужно про это знать:
 * - `.env` в `.gitignore`; в публичный репозиторий ключ не попадает. Шаблон — `.env.example`.
 * - В самой сборке ключ лежит открытым текстом: любой, у кого есть архив, может его достать.
 *   Для раздачи нескольким знакомым это нормально (так работает почти любое приложение
 *   с ключом приложения), но выкладывать сборку публично с этим ключом не стоит.
 * - Если ключ утёк или его залимитили — перевыпустите на rawg.io и пересоберите.
 * - Бесплатный тариф RAWG: некоммерческое использование и видимая ссылка на источник
 *   (она есть в настройках и в подвале карточки игры).
 *
 * Пока значение пустое, RAWG показывается как ненастроенный источник, а приложение
 * продолжает работать на Steam — ровно так же, как синхронизация без `google.config.ts`.
 */
const BUNDLED_KEY: string = import.meta.env.MAIN_VITE_RAWG_KEY ?? ''

export function bundledRawgKey(): string {
  return BUNDLED_KEY.trim()
}

export function isRawgConfigured(): boolean {
  return bundledRawgKey().length > 0
}
